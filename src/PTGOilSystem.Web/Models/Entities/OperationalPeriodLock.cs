using System.ComponentModel.DataAnnotations;

namespace PTGOilSystem.Web.Models.Entities;

/// <summary>
/// قفلِ دورهٔ عملیاتی — «تا این تاریخ بسته است».
///
/// چرا جدا از <see cref="FiscalPeriod"/>: آن یکی متعلق به ماژول حسابداری است که با
/// <c>Accounting.Enabled = false</c> خاموش می‌ماند و اصلاً دوره‌ای برای شرکت‌ها نساخته است.
/// دفتری که امروز ماندهٔ واقعی طرف‌حساب‌ها را می‌سازد (<c>LedgerEntries</c>) هیچ مفهومی از
/// «ماه بسته» نداشت، پس گزارشی که ماه پیش به شریک داده شده بود ماه بعد عدد دیگری می‌داد
/// (PTG-P1-01).
///
/// مدلِ عمداً کوچک: یک واترمارک، نه تقویم کامل. یک سطر برای هر بار بستن/بازکردن نگه داشته
/// می‌شود تا تاریخچه بماند، و قفلِ مؤثر «تازه‌ترین سطر فعال» است. تا وقتی هیچ سطری نباشد،
/// رفتار سیستم دقیقاً مثل قبل است — هیچ ثبتی مسدود نمی‌شود.
/// </summary>
public class OperationalPeriodLock : BaseEntity
{
    /// <summary>
    /// آخرین روزِ بسته (شاملِ خودِ همان روز). هر سندی با تاریخِ کوچک‌تر یا مساوی این تاریخ
    /// در دورهٔ بسته می‌افتد.
    /// </summary>
    public DateTime LockedThroughDate { get; set; }

    /// <summary>
    /// سطرِ غیرفعال یعنی «این قفل برداشته شد»؛ سطر حذف نمی‌شود تا چه‌کسی و چه‌وقت باز کرد
    /// در تاریخچه بماند.
    /// </summary>
    public bool IsActive { get; set; } = true;

    /// <summary>دلیلِ بستن یا بازکردن. اجباری است: قفلِ بی‌دلیل قابل بازرسی نیست.</summary>
    [Required, MaxLength(400)]
    public string Reason { get; set; } = "";
}
